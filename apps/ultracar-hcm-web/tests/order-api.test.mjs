import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT=fileURLToPath(new URL('..',import.meta.url));
const wait=ms=>new Promise(r=>setTimeout(r,ms));
test('private pending order API with same-origin, idempotency and server-side totals',async t=>{
 const dir=await mkdtemp(join(tmpdir(),'ultracarhcm-order-test-'));
 const port=24000+Math.floor(Math.random()*18000);
 const server=spawn(process.execPath,['server.mjs'],{cwd:ROOT,env:{...process.env,PORT:String(port),ULTRACAR_ORDERS_DIR:dir},stdio:'ignore',windowsHide:true});
 t.after(async()=>{server.kill();await wait(130);await rm(dir,{recursive:true,force:true});});
 const base='http://127.0.0.1:'+port;
 let healthy=false;
 for(let n=0;n<65;n++){try{const r=await fetch(base+'/healthz');if(r.status===200){healthy=true;break}}catch{}await wait(100)}
 assert.ok(healthy,'staging server should start');
 const origin=base;
 const data={name:'Khach Kiem Thu',phone:'0901234567',address:'123 Duong Thu Nghiem, Phuong 2, TP HCM',car:'VinFast VF5',note:'test only',method:'bank',requestId:'17c49cc4-882f-4e79-8f92-2e52c82157ae',items:[{sku:'13GRCB',qty:2}]};
 const post=async d=>fetch(base+'/api/orders',{method:'POST',headers:{'content-type':'application/json',origin},body:JSON.stringify(d)});
 const one=await post({...data,items:[{sku:'13GRCB',qty:2,price:1}]});
 assert.equal(one.status,201);
 const receipt=await one.json();
 assert.match(receipt.orderId,/^UC[0-9A-Z]+$/);
 assert.equal(receipt.status,'pending_confirmation');
 assert.equal(receipt.paymentStatus,'unpaid');
 assert.equal(receipt.paymentMethod,'bank');
 assert.equal(receipt.finalAmount,null);
 const catalog=JSON.parse(await readFile(join(ROOT,'products.json'),'utf8'));
 assert.equal(receipt.subtotal,catalog.find(x=>x.sku==='13GRCB').price*2,'price must be trusted server-side');
 assert.doesNotMatch(JSON.stringify(receipt),/Khach Kiem Thu|0901234567|Duong Thu Nghiem/);
 const duplicate=await post(data);assert.equal(duplicate.status,200);
 const again=await duplicate.json();assert.equal(again.orderId,receipt.orderId);assert.equal(again.duplicate,true);
 const bad=await post({...data,requestId:'17c49cc4-882f-4e79-8f92-2e52c82157af',items:[{sku:'NO_SUCH_SKU',qty:1}]});assert.equal(bad.status,422);
 const cross=await fetch(base+'/api/orders',{method:'POST',headers:{'content-type':'application/json',origin:'https://example.org'},body:JSON.stringify({...data,requestId:'17c49cc4-882f-4e79-8f92-2e52c82157ad'})});assert.equal(cross.status,403);
 const forwarded=await fetch(base+'/api/orders',{method:'POST',headers:{'content-type':'application/json',origin:'https://ultracar.tigeriq.io.vn'},body:JSON.stringify({...data,requestId:'17c49cc4-882f-4e79-8f92-2e52c82157ab',method:'cod'})});assert.equal(forwarded.status,201,'canonical public Origin must work even if reverse proxy Host is loopback');
 const forwardedResult=await forwarded.json();assert.equal(forwardedResult.paymentStatus,'unpaid');
 const listing=await fetch(base+'/api/orders');assert.equal(listing.status,405);
 const publicFile=await fetch(base+'/Data/UltraCarHCM/orders.jsonl');assert.equal(publicFile.status,404);
 const qr=await fetch(base+'/assets/mb-vietqr-owner.svg');assert.equal(qr.status,200);
 const log=await readFile(join(dir,'orders.jsonl'),'utf8');
 const lines=log.trim().split('\n').map(x=>JSON.parse(x));
 assert.equal(lines.length,2,'idempotency must avoid double order; canonical Host must succeed');
 assert.equal(lines[0].customer.name,'Khach Kiem Thu');
 assert.equal(lines[0].paymentStatus,'unpaid');
});
